#!/usr/bin/env python3
"""Regenerate the golden CSVs in tests/data from the Python reference solver.

Runs the reference repository's own FEM command-line tool
(`python -m src.training.run_fem`) for each case below and copies its output
here, together with a provenance file that records the reference commit.

Usage (from any directory, with the reference repo's environment active):

    python scripts/generate_golden.py --reference /path/to/pinn-vs-fem-1d-bar
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent.parent / "tests" / "data"

# name -> arguments for run_fem. The C++ test (tests/test_golden.cpp) sets up
# the same problems; keep both lists in sync.
CASES: dict[str, list[str]] = {
    # Two-layer E, tapered A, sine load; clamped left end, free right end.
    "hetero_neumann": [
        "--case", "hetero",
        "--left-type", "dirichlet", "--u0", "0.0",
        "--right-type", "neumann", "--PL", "0.0",
    ],
    # Same bar on a spring at the right end (examples/hetero_robin.yaml).
    "hetero_robin": [
        "--case", "hetero",
        "--left-type", "dirichlet", "--u0", "0.0",
        "--right-type", "robin", "--alphaL", "10.0", "--betaL", "1.0", "--gL", "0.0",
    ],
    # Force at the left end, non-zero displacement at the right end, finer mesh.
    "hetero_mixed_fine": [
        "--case", "hetero", "--elements", "200",
        "--left-type", "neumann", "--P0", "0.5",
        "--right-type", "dirichlet", "--uL", "0.2",
    ],
}


def git(reference: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=reference, check=True, capture_output=True, text=True
    ).stdout.strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--reference", type=Path, required=True,
                        help="path to a checkout of pinn-vs-fem-1d-bar")
    args = parser.parse_args()
    reference = args.reference.resolve()

    commit = git(reference, "rev-parse", "HEAD")
    dirty = subprocess.run(["git", "diff", "--quiet", "HEAD"], cwd=reference).returncode != 0
    if dirty:
        print("warning: the reference repository has uncommitted changes", file=sys.stderr)

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    commands = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, case_args in CASES.items():
            out = Path(tmp) / name
            command = [sys.executable, "-m", "src.training.run_fem", *case_args, "--out", str(out)]
            subprocess.run(command, cwd=reference, check=True, capture_output=True)
            shutil.copyfile(out / "fem_hetero.csv", DATA_DIR / f"{name}.csv")
            commands.append(f"python -m src.training.run_fem {' '.join(case_args)}")
            print(f"wrote tests/data/{name}.csv")

    provenance = [
        "# Golden data",
        "",
        "Generated by `scripts/generate_golden.py` from the Python reference solver",
        "[pinn-vs-fem-1d-bar](https://github.com/alireza-fllh/pinn-vs-fem-1d-bar)",
        f"at commit `{commit}`{' (with uncommitted changes)' if dirty else ''}.",
        "",
        "| File | Command |",
        "|---|---|",
        *(f"| `{name}.csv` | `{cmd}` |" for name, cmd in zip(CASES, commands)),
        "",
    ]
    (DATA_DIR / "README.md").write_text("\n".join(provenance))
    print("wrote tests/data/README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
